
"""
    ImaginaryMajoranaRotation(ms::MajoranaString{TT}) where {TT<:Integer}
    ImaginaryMajoranaRotation(ms_int::TT) where {TT<:Integer}

Structure to represent an imaginary-time Majorana rotation ``e^{-\\beta/2 \\, ms}``, generated by a Majorana string `ms` of even weight.
Applied to a MajoranaSum ``A`` as the two-sided non-unitary conjugation ``e^{-\\beta/2 \\, ms} \\, A \\, e^{-\\beta/2 \\, ms}``.
Only defined in the Schrödinger picture, i.e. `propagate` must be called with `heisenberg=false`.
"""
struct ImaginaryMajoranaRotation{TT<:Integer} <: ParametrizedGate
    ms_int::TT
    function ImaginaryMajoranaRotation(ms::MajoranaString{TT}) where {TT<:Integer}
        iseven(get_weight(ms)) || throw(ArgumentError("ImaginaryMajoranaRotation requires an even-weight Majorana string, got weight $(get_weight(ms))"))
        return new{TT}(ms.gammas)
    end
    function ImaginaryMajoranaRotation(ms_int::TT) where {TT<:Integer}
        iseven(get_weight(ms_int)) || throw(ArgumentError("ImaginaryMajoranaRotation requires an even-weight Majorana string, got weight $(get_weight(ms_int))"))
        return new{TT}(ms_int)
    end
end


"""
    ImaginaryFermionicRotation(symbol::Symbol, sites::Vector{Int})
    ImaginaryFermionicRotation(symbol::Symbol, site::Integer)

Structure to represent the imaginary-time evolution ``e^{-\\beta/2 \\, O}``, generated by the observable ``O`` defined by `symbol` acting on `sites` (with its identity component dropped).
Applied to a MajoranaSum ``A`` as the two-sided non-unitary conjugation ``e^{-\\beta/2 \\, O} \\, A \\, e^{-\\beta/2 \\, O}``.
Note that the exponent carries a factor ``1/2``, in contrast to the real-time `FermionicRotation`.
Only defined in the Schrödinger picture, i.e. `propagate` must be called with `heisenberg=false`.
See `MajoranaSum(n_sites::Integer, symb::Symbol, sites)` for the supported symbols.
"""
struct ImaginaryFermionicRotation <: ParametrizedGate
    symbol::Symbol
    sites::Vector{Int}
end

function ImaginaryFermionicRotation(symbol::Symbol, site::Integer)
    return ImaginaryFermionicRotation(symbol, [site])
end

function PauliPropagation._toheisenberg(gate::Union{ImaginaryFermionicRotation,ImaginaryMajoranaRotation}, τ)
    throw(error("$(typeof(gate)) gates are currently not defined in the Heisenberg picture."))
end

function PauliPropagation._toschrodinger(gate::Union{ImaginaryFermionicRotation,ImaginaryMajoranaRotation}, τ)
    return gate, τ
end

"""
    getmajoranarotations(gate::ImaginaryFermionicRotation, n_sites::Integer)

Given an `ImaginaryFermionicRotation`, returns a tuple `(rotations, coefficients, truncate_after_each_majrot)` with the `ImaginaryMajoranaRotation`s and coefficients that the gate decomposes into.
"""
function getmajoranarotations(gate::ImaginaryFermionicRotation, n_sites::Integer)
    # construct msum encoding the fermionic gate
    msum = MajoranaSum(n_sites, gate.symbol, gate.sites)
    TT = getinttype(nfermions(msum))
    truncate_after_each_majrot = !flag_non_number_preserving(gate.symbol)

    #remove coefficient associated to identity
    pop_id!(msum)

    rotations::Vector{ImaginaryMajoranaRotation{TT}} = []
    coefficients::Vector{Float64} = []
    for (ms, coeff) in msum
        push!(rotations, ImaginaryMajoranaRotation(ms))
        push!(coefficients, coeff)
    end

    return rotations, coefficients, truncate_after_each_majrot
end

"""
Implement the imaginary-time evolution ``e^{-\\beta \\, O / 2} \\, msum \\, e^{-\\beta \\, O / 2}`` for a fermionic gate ``O``.
If `normalize_coeffs=true`, the Majorana sum is renormalized after each Majorana rotation such that the identity coefficient stays 1.
"""
function PropagationBase.applymergetruncate!(gate::ImaginaryFermionicRotation, prop_cache::AbstractMajoranaPropagationCache, beta; truncate_each_mr=nothing, normalize_coeffs=true, thread::Bool=true, kwargs...)
    # get the Majorana strings and coefficients corresponding to the fermionic gate
    ms_rotations, coeffs, truncate_after_each_majrot = getmajoranarotations(gate, nsites(prop_cache))
    if !isnothing(truncate_each_mr)
        truncate_after_each_majrot = truncate_each_mr
    end
    truncfunc, termdrop = _truncfuncs(prop_cache; thread, kwargs...)

    # iterate over individual Majorana rotations and apply them to the Majorana sum
    for (k, (gate_ms, coeff)) in enumerate(zip(ms_rotations, coeffs))
        truncates = truncate_after_each_majrot || k == length(ms_rotations)
        mask = _branchmask(gate_ms, prop_cache)
        rule = _branchrule(gate_ms, prop_cache, beta * coeff)

        # the new strings are gate ⊻ (an ascending run of the sorted strings), so the XOR merge sorts them in
        # as in real time; a step that truncates does not make the new strings rejected for their weight or unpaired Majoranas
        xorbranch!(truncates ? _dropproducts(rule, mask, termdrop) : rule, prop_cache, mask; thread)
        xormerge!(prop_cache, mask; thread)

        # normalize coefficients to preserve state normalization
        if normalize_coeffs
            mult!(prop_cache, 1 / getcoeff(activesum(prop_cache), 0); thread)
        end

        # truncate after each Majorana rotation, or after the last one
        if truncates
            truncate!(truncfunc, prop_cache; thread)
        end
    end

    return prop_cache
end

"""
Implement ``e^{-\\beta \\, G / 2} \\, msum \\, e^{-\\beta \\, G / 2}`` for imaginary time evolution with a Majorana rotation string ``G``.
For a Majorana string ``ms``, the splitting rule is
- ``ms``, if ``\\{G, ms\\} = 0``
- ``\\cosh(\\beta) \\, ms - \\sinh(\\beta) \\, G \\, ms``, if ``[G, ms] = 0``
"""
function PropagationBase.applytoall!(gate::ImaginaryMajoranaRotation, prop_cache::AbstractMajoranaPropagationCache, beta; thread::Bool=true, kwargs...)
    return xorbranch!(_branchrule(gate, prop_cache, beta), prop_cache, _branchmask(gate, prop_cache); thread)
end

# bare imaginary rotations branch, merge and truncate in one call, without normalizing
function PropagationBase.applymergetruncate!(gate::ImaginaryMajoranaRotation, prop_cache::AbstractMajoranaPropagationCache, beta; thread::Bool=true, kwargs...)
    truncfunc, termdrop = _truncfuncs(prop_cache; thread, kwargs...)
    _xorbranchstep!(gate, prop_cache, beta, truncfunc, termdrop; thread)
    return prop_cache
end

# the rule of an imaginary Majorana rotation for `xorbranch!`
function _branchrule(gate::ImaginaryMajoranaRotation, prop_cache, beta)
    gate_ms = _branchmask(gate, prop_cache)
    gate_ms_ps = compute_parity_bits_and_shift(gate_ms, 2 * nfermions(prop_cache))
    return _imaginaryrotationrule(gate_ms, gate_ms_ps, omega_L_mult(gate_ms), cosh(beta), -sinh(beta))
end

# In imaginary time a string splits upon commutation: it keeps cosh(β) of its coefficient and branches into
# its product with the gate, which gets ∓sinh(β).
function _imaginaryrotationrule(gate_ms, gate_ms_ps, omega_l_gate, cosh_val, sinh_val)
    function rotate(term, coeff)
        if !_commutes_evengate(term, gate_ms)
            return Unchanged()
        end
        _, sign = _rotationproduct_evengate_commuting(term, gate_ms, gate_ms_ps, omega_l_gate)
        return Branch(coeff * cosh_val, coeff * sinh_val * sign)
    end
    return rotate
end
